import re,sys,os,urllib.request
css=open(sys.argv[1]).read(); out=sys.argv[2]
keep={"latin","latin-ext"}
faces=[]
for name,b in re.findall(r'/\*\s*([a-z0-9-]+)\s*\*/\s*(@font-face\s*\{[^}]*\})',css):
    if name not in keep: continue
    fam=re.search(r"font-family:\s*'([^']+)'",b).group(1)
    sty=re.search(r"font-style:\s*(\w+)",b).group(1)
    url=re.search(r"url\((https://[^)]+\.woff2)\)",b).group(1)
    rng=re.search(r"unicode-range:\s*([^;]+);",b).group(1).strip()
    wght=re.search(r"font-weight:\s*([^;]+);",b).group(1).strip()
    base="bodoni-moda" if fam.startswith("Bodoni") else "plus-jakarta-sans"
    faces.append((fam,sty,wght,rng,f"{base}-{sty}-{name}.woff2",url))
req=lambda u: urllib.request.Request(u,headers={"User-Agent":"Mozilla/5.0"})
for fam,sty,wght,rng,fn,url in faces:
    with urllib.request.urlopen(req(url),timeout=30) as r: data=r.read()
    open(os.path.join(out,fn),"wb").write(data)
    print(f"  {fn:44s} {len(data)//1024:4d} KB")
L=["/* Booked In — self-hosted type.",
   " *",
   " * Fetched from Google Fonts once and served from our own origin, so no page",
   " * reaches a third party to render. That is one fewer DNS lookup, connection",
   " * and round trip on a first visit, and it is what lets the privacy notice say",
   " * nothing leaves this site: a Google-hosted stylesheet hands a client's IP",
   " * address to Google on every booking page she opens.",
   " *",
   " * Both families are variable, so one file covers the whole weight range. Only",
   " * the latin and latin-ext subsets are kept — enough for English plus the",
   " * accented names common in the UK — and the browser fetches latin-ext only",
   " * when a character actually needs it.",
   " *",
   " * Generated by scripts/fetch-fonts.sh; do not hand-edit.",
   " */"]
for fam,sty,wght,rng,fn,url in faces:
    L+= ["@font-face{", f"  font-family:'{fam}';", f"  font-style:{sty};",
         f"  font-weight:{wght};"]
    if fam.startswith("Bodoni"): L.append("  font-optical-sizing:auto;")
    L+= ["  font-display:swap;", f"  src:url('fonts/{fn}') format('woff2');",
         f"  unicode-range:{rng};", "}"]
open("site/fonts.css","w").write("\n".join(L)+"\n")
print("\nsite/fonts.css:", len(faces), "faces")
